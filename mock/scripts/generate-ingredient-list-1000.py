# Embedded candidate list (1200+ tuples of name, category)
CANDIDATES: list[tuple[str, str]] = build_pool()  # 1420 embedded entries


def normalize_name(name: str) -> str:
    s = unicodedata.normalize("NFKC", name).strip()
    return re.sub(r"[（(].*?[）)]", "", s)


def load_existing_names() -> set[str]:
    names: set[str] = set()
    for path in (EXISTING_200, EXISTING_800):
        for item in json.loads(path.read_text(encoding="utf-8")):
            names.add(normalize_name(item["name"]))
    return names


def filter_candidates(
    candidates: list[tuple[str, str]], existing: set[str]
) -> list[tuple[str, str]]:
    seen: set[str] = set()
    filtered: list[tuple[str, str]] = []
    for name, category in candidates:
        key = normalize_name(name)
        if not key or key in existing or key in seen:
            continue
        seen.add(key)
        filtered.append((name, category))
    return filtered


def write_excel(items: list[tuple[str, str]], path: Path) -> None:
    wb = openpyxl.Workbook()
    ws = wb.active
    ws.title = "食材一覧"
    headers = ["No", "食材名", "カテゴリ"]
    header_font = Font(bold=True)
    for col, header in enumerate(headers, start=1):
        cell = ws.cell(row=1, column=col, value=header)
        cell.font = header_font
        cell.alignment = Alignment(horizontal="center")
    for idx, (name, category) in enumerate(items, start=1):
        ws.cell(row=idx + 1, column=1, value=idx)
        ws.cell(row=idx + 1, column=2, value=name)
        ws.cell(row=idx + 1, column=3, value=category)
    ws.column_dimensions["A"].width = 8
    ws.column_dimensions["B"].width = 36
    ws.column_dimensions["C"].width = 22
    path.parent.mkdir(parents=True, exist_ok=True)
    wb.save(path)


def main() -> None:
    existing = load_existing_names()
    if len(CANDIDATES) < 1200:
        raise SystemExit(f"CANDIDATES must have at least 1200 entries, got {len(CANDIDATES)}")

    filtered = filter_candidates(CANDIDATES, existing)
    if len(filtered) < 1000:
        raise SystemExit(
            f"Need 1000 unique new ingredients, only {len(filtered)} after filtering "
            f"(existing={len(existing)}, raw candidates={len(CANDIDATES)})"
        )

    selected = filtered[:1000]
    write_excel(selected, OUT_PATH)

    categories = Counter(cat for _, cat in selected)
    print(f"Wrote {len(selected)} rows to {OUT_PATH}")
    print("\nFirst 10:")
    for i, (name, cat) in enumerate(selected[:10], start=1):
        print(f"  {i:4d}. {name} ({cat})")
    print("\nLast 10:")
    for i, (name, cat) in enumerate(selected[-10:], start=len(selected) - 9):
        print(f"  {i:4d}. {name} ({cat})")
    print("\nCount by category:")
    for cat, count in sorted(categories.items(), key=lambda x: (-x[1], x[0])):
        print(f"  {cat}: {count}")


if __name__ == "__main__":
    main()
